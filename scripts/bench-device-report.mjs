#!/usr/bin/env node
// The device benchmark's bookkeeping: turns what a runner measured into a result file, and the result
// files into the Markdown of bench/RESULTS.md's device section. No dependencies (Node 22+).
//
//   node scripts/bench-device-report.mjs finalize --raw raw.json --platform ios --target ios-simulator-iphone-17-pro \
//        --kind simulator --label "iPhone 17 Pro simulator" --commit abc1234 [--dirty] [--command "..."] \
//        [--load-before 2.1] [--load-after 2.4] [--tag run2] [--date 2026-10-01] [--out bench/results/device]
//   node scripts/bench-device-report.mjs render [--check]
//   node scripts/bench-device-report.mjs validate FILE...
//   node scripts/bench-device-report.mjs assemble --platform ios --log xcodebuild.log [--attachments DIR] --out raw.json
//   node scripts/bench-device-report.mjs assemble --platform android --out raw.json FULL.txt COLD.txt...
//   node scripts/bench-device-report.mjs get FILE path.to.field
//
// `finalize` wraps the runner's object (schema `undra-device-bench-raw/1`: the operations, the drain
// experiment, the cold start, what the platform said about itself) with what only the script knows (the commit, the
// date, the host's load, the build types) into `bench/results/device/<date>-<target>[-<tag>].json`
// (schema `undra-device-bench/1`). `render` rewrites the block between the markers in bench/RESULTS.md from every such
// file; `render --check` fails when the committed block is not what the files say. `scripts/bench-device.sh`
// calls both; the format is documented in bench/RESULTS.md ("Device numbers").

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const RESULTS_MD = join(ROOT, "bench", "RESULTS.md");
export const RESULTS_DIR = join(ROOT, "bench", "results", "device");
export const TARGETS_FILE = join(ROOT, "bench", "device-targets.json");
export const BEGIN = "<!-- device-bench:begin (generated by scripts/bench-device-report.mjs render; edit nothing between the markers) -->";
export const END = "<!-- device-bench:end -->";

export const RAW_SCHEMA = "undra-device-bench-raw/1";
export const SCHEMA = "undra-device-bench/1";
export const KINDS = ["device", "simulator", "emulator", "browser"];
export const PLATFORMS = ["ios", "android", "web"];
/** The operations every platform's result must carry. */
export const REQUIRED_OPS = ["sync_call", "record_1kb", "keyed_insert_10k", "changeset_100"];
export const NOT_A_DEVICE =
  "Not a device: simulator, emulator or desktop browser on a Mac. Real-device rows are pending hardware, and no claim of meeting a device target is made from this file.";
const FRAME_NS = 1e9 / 60;

// ---- small helpers ------------------------------------------------------------------------------

const isNum = (v) => typeof v === "number" && Number.isFinite(v);

/** `1234` as `1.23 µs`: three significant figures, in the largest unit that keeps the number at least 1, without trailing zeros (`3000` is `3 µs`). */
export function fmtNs(ns) {
  if (!isNum(ns)) return "n/a";
  const abs = Math.abs(ns);
  const sig = (v) => {
    const text = Math.abs(v) >= 100 ? v.toFixed(0) : Math.abs(v) >= 10 ? v.toFixed(1) : v.toFixed(2);
    return text.includes(".") ? text.replace(/\.?0+$/, "") : text;
  };
  if (abs < 1e3) return `${sig(ns)} ns`;
  if (abs < 1e6) return `${sig(ns / 1e3)} µs`;
  return `${sig(ns / 1e6)} ms`;
}

/** The blueprint target of an operation for a platform, in ns, and the note that goes with it; `null` when there is none. */
export function targetFor(targets, platform, id) {
  let key = id;
  let row = targets.rows[id];
  if (platform === "web") {
    // The web's "in-thread" target belongs to the runtime's own synchronous call, not to the asynchronous generated one.
    if (row !== undefined && row.web_applies_to !== undefined && row.web_applies_to !== id) return null;
    if (row === undefined) {
      key = Object.keys(targets.rows).find((k) => targets.rows[k].web_applies_to === id);
      row = key === undefined ? undefined : targets.rows[key];
    }
  }
  if (row === undefined) return null;
  const ns = row[`${platform}_ns`];
  if (!isNum(ns)) return null;
  return { ns, note: row[`${platform}_note`] ?? "" };
}

/** The blueprint's name of the row an operation measures (an extra row has its own). */
export function rowName(targets, id) {
  return targets.rows[id]?.row ?? targets.extra_rows?.[id]?.row ?? id;
}

/** A short name for the notes and the reproducibility lines. */
export function shortName(targets, id) {
  return targets.rows[id]?.short ?? targets.extra_rows?.[id]?.short ?? id;
}

export function readTargets() {
  return JSON.parse(readFileSync(TARGETS_FILE, "utf8"));
}

// ---- validation -------------------------------------------------------------------------------

const SUMMARY_KEYS = ["n", "min", "p50", "p90", "p99", "max", "mean"];

function checkSummary(where, s, problems) {
  if (s === null || typeof s !== "object") return problems.push(`${where}: not a summary`);
  for (const k of SUMMARY_KEYS) if (!isNum(s[k])) problems.push(`${where}.${k} is not a finite number`);
}

/** The problems with a raw runner result (`undra-device-bench-raw/1`); an empty list means it is fit to finalize. */
export function validateRaw(raw) {
  const problems = [];
  if (raw?.schema !== RAW_SCHEMA) problems.push(`schema is ${JSON.stringify(raw?.schema)}, not ${RAW_SCHEMA}`);
  if (!PLATFORMS.includes(raw?.platform)) problems.push(`platform ${JSON.stringify(raw?.platform)} is not one of ${PLATFORMS.join(", ")}`);
  if (!Array.isArray(raw?.ops)) return [...problems, "ops is not a list"];
  const ids = new Set();
  for (const op of raw.ops) {
    ids.add(op?.id);
    for (const k of ["batch", "samples", "min", "p50", "p90", "p99", "max", "mean"]) {
      if (!isNum(op?.[k])) problems.push(`op ${op?.id}: ${k} is not a finite number`);
    }
    if (!["each", "batched"].includes(op?.mode)) problems.push(`op ${op?.id}: mode ${JSON.stringify(op?.mode)}`);
    if (isNum(op?.p50) && isNum(op?.p99) && op.p99 < op.p50) problems.push(`op ${op?.id}: p99 ${op.p99} is below p50 ${op.p50}`);
    if (isNum(op?.samples) && op.samples < 1) problems.push(`op ${op?.id}: no samples`);
  }
  for (const id of REQUIRED_OPS) if (!ids.has(id)) problems.push(`op ${id} is missing`);
  if (raw.timer === undefined || !isNum(raw.timer.resolution_ns) || !isNum(raw.timer.overhead_ns)) problems.push("timer facts are missing");
  const d = raw.drain;
  if (d === undefined || d === null) {
    problems.push("the drain experiment is missing");
  } else {
    checkSummary("drain.merged.frame_ns", d.merged?.frame_ns, problems);
    checkSummary("drain.merged.drain_ns", d.merged?.drain_ns, problems);
    checkSummary("drain.unmerged_estimate.per_entry_ns", d.unmerged_estimate?.per_entry_ns, problems);
    for (const k of ["change_sets_per_frame_p50", "entries_per_frame_p50", "applied_per_frame_p50", "drains_per_frame_p50"]) {
      if (!isNum(d.merged?.[k])) problems.push(`drain.merged.${k} is not a finite number`);
    }
    if (!isNum(d.unmerged_estimate?.frame_ns)) problems.push("drain.unmerged_estimate.frame_ns is not a finite number");
    if (!isNum(d.ratio_unmerged_over_merged)) problems.push("drain.ratio_unmerged_over_merged is not a finite number");
  }
  const c = raw.cold;
  if (c !== undefined && c !== null) {
    if (!Array.isArray(c.launches)) problems.push("cold.launches is not a list");
    else for (const [i, l] of c.launches.entries()) if (!isNum(l?.load_ns)) problems.push(`cold.launches[${i}].load_ns is not a finite number`);
  }
  if (typeof raw.device !== "object" || raw.device === null) problems.push("device facts are missing");
  return problems;
}

/** The problems with a finished result file. */
export function validateResult(result) {
  const problems = [];
  if (result?.schema !== SCHEMA) problems.push(`schema is ${JSON.stringify(result?.schema)}, not ${SCHEMA}`);
  if (!KINDS.includes(result?.kind)) problems.push(`kind ${JSON.stringify(result?.kind)} is not one of ${KINDS.join(", ")}`);
  for (const k of ["date", "target", "label", "command"]) if (typeof result?.[k] !== "string" || result[k] === "") problems.push(`${k} is missing`);
  if (typeof result?.build?.commit !== "string") problems.push("build.commit is missing");
  if (typeof result?.build?.type !== "string") problems.push("build.type is missing");
  if (result?.kind !== undefined && result.kind !== "device" && result.claim !== NOT_A_DEVICE) {
    problems.push("a result that is not from a device must carry the not-a-device claim verbatim");
  }
  return [...problems, ...validateRaw({ ...result, schema: RAW_SCHEMA })];
}

// ---- assembling what the platforms printed ----------------------------------------------------

const RESULT_PREFIX = "UNDRA_BENCH_RESULT ";
const ANDROID_PREFIX = "INSTRUMENTATION_STATUS: undra_bench_json=";
export const COLD_SCHEMA = "undra-device-bench-cold/1";

/** The JSON objects an iOS UI test printed (`UNDRA_BENCH_RESULT {json}` lines) in `text`, in order. */
export function resultsFromLog(text) {
  const out = [];
  for (const line of text.split("\n")) {
    const at = line.indexOf(RESULT_PREFIX);
    if (at >= 0) out.push(JSON.parse(line.slice(at + RESULT_PREFIX.length)));
  }
  return out;
}

/** The JSON objects an instrumentation run printed (`INSTRUMENTATION_STATUS: undra_bench_json=...` lines) in `text`. */
export function resultsFromInstrumentation(text) {
  return text
    .split("\n")
    .filter((line) => line.startsWith(ANDROID_PREFIX))
    .map((line) => JSON.parse(line.slice(ANDROID_PREFIX.length)));
}

/** The JSON objects an `xcresulttool export attachments` directory holds, in the order of the attachments' names (`bench-full-0`, `bench-cold-1`, ...). */
export function resultsFromAttachments(dir) {
  const manifest = JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8"));
  const found = [];
  for (const test of manifest) {
    for (const a of test.attachments ?? []) {
      const m = /^bench-(full|cold)-(\d+)/.exec(a.suggestedHumanReadableName ?? "");
      if (m) found.push({ order: Number(m[2]), json: JSON.parse(readFileSync(join(dir, a.exportedFileName), "utf8")) });
    }
  }
  return found.sort((a, b) => a.order - b.order).map((f) => f.json);
}

/** The runner's raw result from a full run and the cold launches that followed it: each cold result becomes an entry of `cold.launches`. */
export function assemble(results) {
  const full = results.filter((r) => r.schema === RAW_SCHEMA);
  const colds = results.filter((r) => r.schema === COLD_SCHEMA);
  if (full.length !== 1) throw new Error(`expected exactly one full result, found ${full.length}`);
  const raw = structuredClone(full[0]);
  raw.cold = raw.cold ?? { launches: [] };
  raw.cold.launches = colds.map((c) => ({ load_ns: c.load_ns, ...(isNum(c.restore_ns) ? { restore_ns: c.restore_ns } : {}) }));
  const sizes = new Set(colds.map((c) => c.snapshot_bytes).filter(isNum));
  if (sizes.size > 1) throw new Error(`the cold launches restored snapshots of different sizes: ${[...sizes].join(", ")}`);
  if (sizes.size === 1 && isNum(raw.cold.snapshot_bytes) && !sizes.has(raw.cold.snapshot_bytes)) {
    throw new Error("the cold launches did not restore the snapshot the full run wrote");
  }
  return raw;
}

// ---- finalize -------------------------------------------------------------------------------

function parseFlags(argv) {
  const flags = {};
  const rest = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith("--")) {
      const name = a.slice(2);
      const next = argv[i + 1];
      if (next === undefined || next.startsWith("--")) flags[name] = true;
      else {
        flags[name] = next;
        i++;
      }
    } else rest.push(a);
  }
  return { flags, rest };
}

/** Builds the finished result from a raw runner result and what the script knows. */
export function finalize(raw, meta) {
  const problems = validateRaw(raw);
  if (problems.length > 0) throw new Error(`the runner's result is not valid:\n  ${problems.join("\n  ")}`);
  if (!KINDS.includes(meta.kind)) throw new Error(`--kind must be one of ${KINDS.join(", ")}`);
  const result = {
    schema: SCHEMA,
    date: meta.date,
    finished_at: meta.finishedAt,
    target: meta.target,
    platform: raw.platform,
    kind: meta.kind,
    label: meta.label,
    claim: meta.kind === "device" ? "Measured on a device." : NOT_A_DEVICE,
    device: raw.device,
    host: meta.host ?? null,
    build: { type: meta.buildType, core: meta.core, app: meta.app, commit: meta.commit, dirty: meta.dirty },
    command: meta.command,
    runtime: raw.runtime,
    timer: raw.timer,
    config: raw.config,
    ops: raw.ops,
    cold: raw.cold ?? null,
    drain: raw.drain,
    notes: [...(raw.notes ?? []), ...(meta.notes ?? [])],
  };
  const bad = validateResult(result);
  if (bad.length > 0) throw new Error(`the result is not valid:\n  ${bad.join("\n  ")}`);
  return result;
}

// ---- rendering -------------------------------------------------------------------------------

/** Every result file under `dir`, parsed, in file-name order. */
export function loadResults(dir = RESULTS_DIR) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => ({ file: f, result: JSON.parse(readFileSync(join(dir, f), "utf8")) }))
    .filter(({ result }) => result.schema === SCHEMA);
}

const ORDER = { ios: 0, android: 1, web: 2 };
const KIND_ORDER = { device: 0, simulator: 1, emulator: 1, browser: 2 };

/** For each target, the files of its latest date, oldest run first. */
export function latestPerTarget(files) {
  const byTarget = new Map();
  for (const f of files) {
    const list = byTarget.get(f.result.target) ?? [];
    list.push(f);
    byTarget.set(f.result.target, list);
  }
  const groups = [];
  for (const list of byTarget.values()) {
    const newestDate = list.map((f) => f.result.date).sort().at(-1);
    const runs = list
      .filter((f) => f.result.date === newestDate)
      .sort((a, b) => String(a.result.finished_at ?? a.file).localeCompare(String(b.result.finished_at ?? b.file)));
    groups.push(runs);
  }
  return groups.sort((a, b) => {
    const [x, y] = [a.at(-1).result, b.at(-1).result];
    return (KIND_ORDER[x.kind] - KIND_ORDER[y.kind]) || (ORDER[x.platform] - ORDER[y.platform]) || x.target.localeCompare(y.target);
  });
}

const ROW_ORDER = ["sync_call", "sync_call_runtime", "record_1kb", "keyed_insert_10k", "changeset_100"];

function verdictFor(result, target, p50) {
  if (result.kind === "device") return target === null ? "no target" : p50 <= target.ns ? "within" : `over, ${(p50 / target.ns).toFixed(1)}x`;
  if (result.kind === "browser") return "none (no reference machine)";
  return "none (not a device)";
}

const targetCell = (t) => (t === null ? "n/a" : `≤ ${fmtNs(t.ns)}${t.note ? ` (${t.note})` : ""}`);

function opRows(result, targets) {
  const byId = new Map(result.ops.map((o) => [o.id, o]));
  const ids = [...ROW_ORDER, ...result.ops.map((o) => o.id).filter((id) => !ROW_ORDER.includes(id))].filter((id) => byId.has(id));
  const rows = [];
  for (const id of ids) {
    const op = byId.get(id);
    const t = targetFor(targets, result.platform, id);
    const timing = op.mode === "each" ? "each op" : `batches of ${op.batch}`;
    rows.push(`| ${rowName(targets, id)} | ${fmtNs(op.p50)} | ${fmtNs(op.p99)} | ${timing}, ${op.samples} samples | ${targetCell(t)} | ${verdictFor(result, t, op.p50)} |`);
  }
  const cold = coldRow(result, targets);
  if (cold !== null) rows.push(cold);
  return rows;
}

/** What each row timed, once per result: the notes the runner wrote. */
function opNotes(result, targets) {
  const lines = result.ops.map((op) => `* ${shortName(targets, op.id)}: ${op.note}.`);
  if (result.cold?.note) lines.push(`* Cold start: ${result.cold.note}.`);
  return lines;
}

/** The cold-start row: over the fresh launches. */
function coldRow(result, targets) {
  const c = result.cold;
  if (c === null || c === undefined) return null;
  const t = targetFor(targets, result.platform, "cold_start_100kb");
  const total = (l) => l.load_ns + (isNum(l.restore_ns) ? l.restore_ns : 0);
  const fresh = (c.launches ?? []).map(total).sort((a, b) => a - b);
  if (fresh.length === 0) return null;
  const pct = (xs, p) => xs[Math.min(xs.length - 1, Math.max(0, Math.ceil(p * xs.length - 1e-9) - 1))];
  const restored = (c.launches ?? []).some((l) => isNum(l.restore_ns));
  const name = restored ? rowName(targets, "cold_start_100kb") : `${rowName(targets, "cold_start_100kb")} (**load only: no restore, see the notes**)`;
  return `| ${name} | ${fmtNs(pct(fresh, 0.5))} | ${fmtNs(pct(fresh, 0.99))} | fresh process, ${fresh.length} launch${fresh.length === 1 ? "" : "es"} | ${targetCell(t)} | ${verdictFor(result, t, pct(fresh, 0.5))} |`;
}

function coldDetail(result) {
  const c = result.cold;
  if (c === null || c === undefined) return null;
  const parts = [];
  const med = (xs) => {
    const s = [...xs].sort((a, b) => a - b);
    return s[Math.floor((s.length - 1) / 2)];
  };
  const ls = c.launches ?? [];
  if (ls.length > 0) {
    const loads = ls.map((l) => l.load_ns);
    parts.push(`fresh launches (${ls.length}): load p50 ${fmtNs(med(loads))}, min ${fmtNs(Math.min(...loads))}, max ${fmtNs(Math.max(...loads))}`);
    const restores = ls.map((l) => l.restore_ns).filter(isNum);
    if (restores.length > 0) parts.push(`restore p50 ${fmtNs(med(restores))}`);
    const compiles = ls.map((l) => l.compile_ns).filter(isNum);
    if (compiles.length > 0) parts.push(`wasm compile p50 ${fmtNs(med(compiles))} (not in the row, as the blueprint says)`);
  }
  const r = c.reload_in_process ?? c.reload_in_page;
  if (r?.load_ns?.p50 !== undefined) {
    parts.push(`${c.reload_in_process ? "in-process" : "in-page"} reloads (warm): load p50 ${fmtNs(r.load_ns.p50)}${r.restore_ns?.p50 !== undefined ? `, restore p50 ${fmtNs(r.restore_ns.p50)}` : ""}`);
  }
  if (isNum(c.snapshot_bytes)) parts.push(`snapshot ${c.snapshot_bytes.toLocaleString("en-US")} bytes`);
  return parts.length === 0 ? null : parts.join("; ");
}

function drainTable(groups) {
  const lines = [
    "| Target | Main-thread cost of a frame, merged (p50 / p99) | Entries received → applied | One entry applied on its own (p50) | Estimated unmerged frame | Merging saves | Share of a 60 Hz frame (merged / unmerged) |",
    "|---|---|---|---|---|---|---|",
  ];
  for (const runs of groups) {
    const r = runs.at(-1).result;
    const d = r.drain;
    const m = d.merged;
    const share = (ns) => `${((100 * ns) / FRAME_NS).toFixed(1)}%`;
    lines.push(
      `| ${r.label} | ${fmtNs(m.frame_ns.p50)} / ${fmtNs(m.frame_ns.p99)} | ${m.entries_per_frame_p50.toLocaleString("en-US")} → ${m.applied_per_frame_p50.toLocaleString("en-US")} (${m.drains_per_frame_p50} drain${m.drains_per_frame_p50 === 1 ? "" : "s"}) | ${fmtNs(d.unmerged_estimate.per_entry_ns.p50)} | ${fmtNs(d.unmerged_estimate.frame_ns)} | ${d.ratio_unmerged_over_merged.toFixed(1)}x | ${share(m.frame_ns.p50)} / ${share(d.unmerged_estimate.frame_ns)} |`,
    );
  }
  return lines;
}

function reproducibility(groups, targets) {
  const lines = [];
  for (const runs of groups) {
    if (runs.length < 2) continue;
    const r = runs.at(-1).result;
    const ids = r.ops.map((o) => o.id);
    const cells = ids.map((id) => {
      const ps = runs.map((x) => x.result.ops.find((o) => o.id === id)?.p50).filter(isNum);
      if (ps.length < 2) return null;
      return `${shortName(targets, id)}: ${ps.map(fmtNs).join(" / ")} (${(Math.max(...ps) / Math.min(...ps)).toFixed(2)}x)`;
    });
    const dr = runs.map((x) => x.result.drain.merged.frame_ns.p50);
    lines.push(`* **${r.label}**, ${runs.length} runs (${runs.map((x) => x.file).join(", ")}): median per row, run by run, with the spread: ${cells.filter(Boolean).join("; ")}; merged frame ${dr.map(fmtNs).join(" / ")} (${(Math.max(...dr) / Math.min(...dr)).toFixed(2)}x).`);
  }
  return lines;
}

/** The Markdown between the markers. */
export function renderBlock(files, targets) {
  const groups = latestPerTarget(files);
  const out = [BEGIN, ""];
  if (groups.length === 0) {
    out.push("_No device-bench result files yet: run `scripts/bench-device.sh --device <ios|android|web>`._", "", END);
    return out.join("\n");
  }
  out.push(
    `**Every row below was measured by \`scripts/bench-device.sh\` and is the file named under its heading** (\`bench/results/device/\`). ` +
      `The blueprint targets are beside the numbers for reference. **A row from a simulator, an emulator or a desktop browser makes no claim about a device target: ` +
      `the verdict column says so, and only a row from a physical device gets one.**`,
    "",
  );
  for (const runs of groups) {
    const r = runs.at(-1).result;
    const f = runs.at(-1).file;
    const dev = r.device ?? {};
    const facts = [dev.model && `model ${dev.model}`, dev.os, dev.arch, dev.cores && `${dev.cores} cores`, r.runtime && `runtime: ${r.runtime}`].filter(Boolean);
    const build = [r.build.core && `core ${r.build.core}`, r.build.app && `app ${r.build.app}`].filter(Boolean).join("; ");
    out.push(`#### ${r.label}`, "");
    out.push(
      `${r.kind === "device" ? "**A device.**" : r.kind === "browser" ? "**A desktop browser, not a device.**" : `**A${r.kind === "emulator" ? "n" : ""} ${r.kind}, not a device.**`} \`${f}\`, ${r.date}. ${facts.join(", ")}. ` +
        `Build (${r.build.type}): ${build}; commit \`${r.build.commit}\`${r.build.dirty ? " (uncommitted changes)" : ""}. ` +
        `Timer: ${r.timer.kind}, step ${fmtNs(r.timer.resolution_ns)}, a pair of reads ${fmtNs(r.timer.overhead_ns)}.` +
        (r.host ? ` Host: ${r.host.cpu ?? ""}, ${r.host.os ?? ""}; load average ${r.host.load_before ?? "?"} before the run, ${r.host.load_after ?? "?"} after.` : ""),
      "",
    );
    out.push("| Row | p50 | p99 | Timed as | Blueprint target | Verdict |", "|---|---|---|---|---|---|", ...opRows(r, targets), "");
    const cd = coldDetail(r);
    if (cd) out.push(`Cold start: ${cd}.`, "");
    for (const n of r.notes ?? []) out.push(`* ${n}`);
    if ((r.notes ?? []).length > 0) out.push("");
    out.push("<details><summary>What each row timed</summary>", "", ...opNotes(r, targets), "", "</details>", "");
  }
  out.push(
    "#### The ADR-031 drain: 1,667 one-update keyed patches on 10,000 rows per frame (100,000 a second at 60 Hz)",
    "",
    ...drainTable(groups),
    "",
  );
  for (const runs of groups) {
    const r = runs.at(-1).result;
    out.push(`* **${r.label}.** ${r.drain.producer}. ${r.drain.note}. Unmerged estimate: ${r.drain.unmerged_estimate.method}.`);
  }
  out.push("");
  const repro = reproducibility(groups, targets);
  if (repro.length > 0) out.push("#### Reproducibility", "", ...repro, "");
  const have = new Set(groups.map((g) => `${g.at(-1).result.platform}:${g.at(-1).result.kind}`));
  const pending = [];
  if (!have.has("ios:device")) pending.push(["iOS", targets.devices.ios, "an iPhone with an A15-class chip, attached over USB with a development team"]);
  if (!have.has("android:device")) pending.push(["Android", targets.devices.android, "a 2022 mid-range phone with USB debugging enabled"]);
  if (pending.length > 0) {
    out.push("#### Pending hardware", "", "| Platform | Reference device | What is needed |", "|---|---|---|");
    for (const [p, d, need] of pending) out.push(`| ${p} | ${d} | ${need}; \`scripts/bench-device.sh --device ${p.toLowerCase()} --target <id>\` |`);
    out.push("");
  }
  out.push(END);
  return out.join("\n");
}

/** `markdown` with the block between the markers replaced by `block` (the markers must exist exactly once). */
export function replaceBlock(markdown, block) {
  const a = markdown.indexOf(BEGIN);
  const b = markdown.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error(`bench/RESULTS.md has no ${BEGIN} ... ${END} block`);
  return markdown.slice(0, a) + block + markdown.slice(b + END.length);
}

// ---- command line ---------------------------------------------------------------------------

function main(argv) {
  const [command, ...args] = argv;
  const { flags, rest } = parseFlags(args);
  switch (command) {
    case "finalize": {
      for (const need of ["raw", "platform", "target", "kind", "label", "commit"]) if (typeof flags[need] !== "string") throw new Error(`finalize needs --${need}`);
      const raw = JSON.parse(readFileSync(flags.raw, "utf8"));
      if (raw.platform !== flags.platform) throw new Error(`the runner says platform ${raw.platform}, not ${flags.platform}`);
      const today = new Date().toISOString().slice(0, 10);
      const date = typeof flags.date === "string" ? flags.date : today;
      const num = (v) => (typeof v === "string" && v !== "" && Number.isFinite(Number(v)) ? Number(v) : null);
      const hostFlags = ["host-cpu", "host-os", "load-before", "load-after"].some((k) => typeof flags[k] === "string");
      const meta = {
        date,
        finishedAt: new Date().toISOString(),
        target: flags.target,
        kind: flags.kind,
        label: flags.label,
        commit: flags.commit,
        dirty: flags.dirty === true || flags.dirty === "1",
        command: typeof flags.command === "string" ? flags.command : "scripts/bench-device.sh",
        buildType: typeof flags["build-type"] === "string" ? flags["build-type"] : "release",
        core: typeof flags.core === "string" ? flags.core : "release (LTO fat)",
        app: typeof flags.app === "string" ? flags.app : undefined,
        host: hostFlags
          ? { cpu: flags["host-cpu"], os: flags["host-os"], arch: flags["host-arch"], load_before: num(flags["load-before"]), load_after: num(flags["load-after"]) }
          : null,
        notes: typeof flags.note === "string" ? [flags.note] : [],
      };
      const result = finalize(raw, meta);
      const dir = typeof flags.out === "string" ? resolve(flags.out) : RESULTS_DIR;
      mkdirSync(dir, { recursive: true });
      const tag = typeof flags.tag === "string" && flags.tag !== "" ? `-${flags.tag}` : "";
      const file = join(dir, `${date}-${flags.target}${tag}.json`);
      writeFileSync(file, `${JSON.stringify(result, null, 1)}\n`);
      console.log(`wrote ${relative(process.cwd(), file)}`);
      return 0;
    }
    case "render": {
      // `--dir` and `--md` render other files than the published ones (a preview, the tests).
      const dir = typeof flags.dir === "string" ? resolve(flags.dir) : RESULTS_DIR;
      const md = typeof flags.md === "string" ? resolve(flags.md) : RESULTS_MD;
      const targets = readTargets();
      const block = renderBlock(loadResults(dir), targets);
      const current = readFileSync(md, "utf8");
      const next = replaceBlock(current, block);
      if (flags.check === true) {
        if (next !== current) {
          console.error("bench/RESULTS.md's device block is not what bench/results/device/*.json say: run `node scripts/bench-device-report.mjs render`");
          return 1;
        }
        console.log("bench/RESULTS.md's device block is current");
        return 0;
      }
      if (next !== current) writeFileSync(md, next);
      console.log(`${next === current ? "unchanged" : "updated"}: ${relative(process.cwd(), md)}`);
      return 0;
    }
    case "assemble": {
      if (typeof flags.out !== "string") throw new Error("assemble needs --out");
      let results;
      if (flags.platform === "ios") {
        const log = typeof flags.log === "string" ? readFileSync(flags.log, "utf8") : "";
        results = resultsFromLog(log);
        if (!results.some((r) => r.schema === RAW_SCHEMA) && typeof flags.attachments === "string") results = resultsFromAttachments(flags.attachments);
      } else if (flags.platform === "android") {
        results = rest.flatMap((file) => resultsFromInstrumentation(readFileSync(file, "utf8")));
      } else throw new Error("assemble --platform ios|android");
      const raw = assemble(results);
      writeFileSync(flags.out, `${JSON.stringify(raw, null, 1)}\n`);
      console.log(`assembled ${flags.out}: ${raw.ops.length} operations, ${raw.cold.launches.length} cold launches`);
      return 0;
    }
    case "get": {
      const value = rest[1].split(".").reduce((o, k) => o?.[k], JSON.parse(readFileSync(rest[0], "utf8")));
      console.log(value === undefined || value === null ? "" : typeof value === "object" ? JSON.stringify(value) : String(value));
      return 0;
    }
    case "validate": {
      let bad = 0;
      for (const file of rest) {
        const parsed = JSON.parse(readFileSync(file, "utf8"));
        const problems = parsed.schema === RAW_SCHEMA ? validateRaw(parsed) : validateResult(parsed);
        if (problems.length > 0) {
          bad++;
          console.error(`${file}:\n  ${problems.join("\n  ")}`);
        } else console.log(`${file}: ok`);
      }
      return bad === 0 ? 0 : 1;
    }
    default:
      console.error("usage: bench-device-report.mjs finalize|render|validate (see the header of this file)");
      return 2;
  }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exit(main(process.argv.slice(2)));
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
